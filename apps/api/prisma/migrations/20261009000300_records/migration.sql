-- ─────────────────────────────────────────────────────────────────────────────
-- Owner scope (doc 48 §5, P1-1a). One definition of "the caller's own records": the member id in
-- `app.owner_member_id`, NULL when the caller's role sees every owner. A RESTRICTIVE policy ANDs
-- with the workspace policy, so an own-scoped caller reaches only rows they own — and can write
-- only rows they own (WITH CHECK), whatever the application layer forgot.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE FUNCTION app_owner_member_id() RETURNS uuid
    LANGUAGE sql STABLE PARALLEL SAFE
    RETURN NULLIF(current_setting('app.owner_member_id', true), '')::uuid;


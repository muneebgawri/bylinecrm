#!/usr/bin/env bash
# bootstrap-secrets.sh — create BylineCRM staging's state directory and environment (P5-4a).
#
# Runs ON the VPS, as root, once (and again safely at any time): it never overwrites a secret that
# already exists and never prints one.
#
# Touches only:
#   $BYLINECRM_RUNTIME (default /opt/bylinecrm-runtime): the directory, data/{postgres,redis,
#   attachments}, postgres.env (0600) and staging.env (0600).
# Nothing of NewswireOS.
#
# Secrets are generated on the box with openssl and stay there: the Postgres owner password, the
# restricted app-role password (both hex, so they need no escaping inside a URL) and SECRETS_KEY
# (32 random bytes, base64 — what the API's env schema requires). Every other value is derived or
# fixed and is rewritten on each run, so changing this script and re-running it updates them.
#
# The variables mirror apps/api/src/config/env.ts; the API refuses to boot on a missing one.

set -euo pipefail

RUNTIME=${BYLINECRM_RUNTIME:-/opt/bylinecrm-runtime}
PUBLIC_URL=${BYLINECRM_PUBLIC_URL:-https://staging.crm.pinionnewswire.com}
# The api image runs as the `node` user (uid 1000, gid 1000); it writes attachments.
API_UID=${BYLINECRM_API_UID:-1000}
API_GID=${BYLINECRM_API_GID:-1000}

APP_ENV="$RUNTIME/staging.env"
PG_ENV="$RUNTIME/postgres.env"

umask 077
mkdir -p "$RUNTIME/data/postgres" "$RUNTIME/data/redis" "$RUNTIME/data/attachments"
chmod 700 "$RUNTIME"
chown "$API_UID:$API_GID" "$RUNTIME/data/attachments"

# Reads KEY's value from FILE, or nothing when the file or the key is absent.
existing() {
    local file=$1 key=$2
    [ -f "$file" ] || return 0
    sed -n "s/^${key}=//p" "$file" | head -n 1
}

# The stored value, or a freshly generated one when there is none yet.
keep_or_generate() {
    local file=$1 key=$2 generator=$3 value
    value=$(existing "$file" "$key")
    if [ -z "$value" ]; then
        value=$($generator)
        echo "bootstrap-secrets: generated ${key}" >&2
    else
        echo "bootstrap-secrets: kept existing ${key}" >&2
    fi
    printf '%s' "$value"
}

hex24() { openssl rand -hex 24; }
key32() { openssl rand -base64 32 | tr -d '\n'; }

PG_PASSWORD=$(keep_or_generate "$PG_ENV" POSTGRES_PASSWORD hex24)
APP_DB_PASSWORD=$(keep_or_generate "$APP_ENV" APP_DB_PASSWORD hex24)
SECRETS_KEY=$(keep_or_generate "$APP_ENV" SECRETS_KEY key32)

# Operator-set (not secret, not derived): the platform admins (P0-14). Pass
# BYLINECRM_PLATFORM_ADMIN_EMAILS to change the list; otherwise the stored list is kept, so a re-run
# never drops it. Empty is valid and means nobody can create a workspace.
if [ -n "${BYLINECRM_PLATFORM_ADMIN_EMAILS+set}" ]; then
    PLATFORM_ADMIN_EMAILS=$BYLINECRM_PLATFORM_ADMIN_EMAILS
    echo "bootstrap-secrets: set PLATFORM_ADMIN_EMAILS from BYLINECRM_PLATFORM_ADMIN_EMAILS" >&2
else
    PLATFORM_ADMIN_EMAILS=$(existing "$APP_ENV" PLATFORM_ADMIN_EMAILS)
    echo "bootstrap-secrets: kept existing PLATFORM_ADMIN_EMAILS" >&2
fi

write_atomically() {
    local target=$1 tmp
    tmp=$(mktemp "${target}.XXXXXX")
    cat >"$tmp"
    chmod 600 "$tmp"
    mv -f "$tmp" "$target"
}

write_atomically "$PG_ENV" <<EOF
# Generated by deploy/staging/bootstrap-secrets.sh — the Postgres container only.
POSTGRES_USER=bylinecrm
POSTGRES_DB=bylinecrm
POSTGRES_PASSWORD=${PG_PASSWORD}
EOF

write_atomically "$APP_ENV" <<EOF
# Generated by deploy/staging/bootstrap-secrets.sh — the api and migrate containers.
# Re-run the script to change a derived value; secrets are kept. Mirrors apps/api/src/config/env.ts.
NODE_ENV=production
APP_DB_PASSWORD=${APP_DB_PASSWORD}
DATABASE_URL=postgresql://bylinecrm:${PG_PASSWORD}@postgres:5432/bylinecrm
RLS_DATABASE_URL=postgresql://bylinecrm_app:${APP_DB_PASSWORD}@postgres:5432/bylinecrm
REDIS_URL=redis://redis:6379
PORT=3000
APP_URL=${PUBLIC_URL}
WEB_URL=${PUBLIC_URL}
FILE_STORAGE_ROOT=/data/attachments
SECRETS_KEY=${SECRETS_KEY}
WEBHOOK_WORKER=1
WEBHOOK_ALLOW_PRIVATE_TARGETS=0
MAIL_SYNC_WORKER=1
MAIL_SEND_WORKER=1
DB_QUERY_EVENTS=0
# Staging's URL is public: sign-up stays closed (docs/deploy/staging.md). Never open.
SIGNUP_MODE=closed
PLATFORM_ADMIN_EMAILS=${PLATFORM_ADMIN_EMAILS}
EOF

echo "bootstrap-secrets: wrote ${PG_ENV} and ${APP_ENV} (0600); no secret was printed" >&2
